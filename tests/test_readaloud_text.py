def _dropped_repeat_or_url_positions(text):
    """정렬표에 없어도 되는 원문 위치: 줄 안에서 같은 글자 4번째부터(반복 줄임), URL 안쪽(HTTP URL. 로 바뀜)."""
    import re
    url = re.compile(r"https?://[^\t\n\x0b\x0c\r    -     　﻿]+")
    exempt = set()
    for line, base in rt.split_lines(text):
        run = 1
        for i in range(1, len(line)):
            c = line[i]
            if c == line[i - 1] and ord(c) <= 0xFFFF and not ("0" <= c <= "9"):
                run += 1
                if run > 3:
                    exempt.add(base + i)
            else:
                run = 1
        for m in url.finditer(line):
            exempt.update(range(base + m.start(), base + m.end()))
    return exempt


def _joined(text):
    parts = []
    for line, _ in rt.split_lines(text):
        line = rt.preprocess(line)
        parts.append(line + "." if rt.needs_period(line) else line)
    return "\n\n".join(parts)


class InvariantTest(unittest.TestCase):
    """모든 조각의 원문 구간이 원문 안에 있고, 서로 겹치지 않고, 순서대로이며, 빠진 글자가 없는지."""

    def check(self, text, lang, voice, words):
        segments = rt.build_segments(text, lang)
        for seg in segments:
            self.assertLessEqual(u16len(seg), rt.CHAR_LIMIT)
            self.assertFalse(any(0xD800 <= ord(c) <= 0xDFFF for c in seg))
        al = rt.align_segments_to_source(text, segments)
        # 정렬 실패(None)는 조각 나누기가 공백 아닌 글자를 떨어뜨렸을 때뿐이다(확장 버릇 (a): 머리의 - / —)
        dropped = bool(segments) and strip_ws("".join(segments)) != strip_ws(_joined(text))
        self.assertEqual(al is None, dropped)
        if al is not None:
            prev_end = 0
            covered = set()
            for i, seg in enumerate(segments):
                r = al.segment_range(i)
                if r is None:
                    # 원문 글자가 없는 조각: 공백뿐이거나, 750자 딱 맞는 공백 없는 줄에 붙인 마침표 하나
                    self.assertIn(strip_ws(seg), ("", "."))
                    continue
                start, end = r
                self.assertTrue(0 <= start < end <= len(text), r)
                self.assertGreaterEqual(start, prev_end)          # 겹치지 않고 순서대로
                prev_end = end
                covered.update(range(start, end))
            exempt = _dropped_repeat_or_url_positions(text)
            missing = [p for p, c in enumerate(text) if c not in JS_WS and p not in covered and p not in exempt]
            self.assertEqual(missing, [])
        result = rt.split_for_reading(text, lang, voice, words)
        self.assertEqual(len(result), len(segments))
        for i, seg in enumerate(segments):
            sp = rt.make_spoken_text(seg, voice or lang, words)
            self.assertEqual(result[i]["text"], sp.text)
            self.assertEqual(len(sp.src), len(sp.text))
            self.assertTrue(all(0 <= v < len(seg) for v in sp.src))
            self.assertTrue(all(sp.src[k] <= sp.src[k + 1] for k in range(len(sp.src) - 1)))
            self.assertEqual(sp.source_index(len(sp.text)), len(seg))
            span = al.segment_range(i) if al is not None else None
            self.assertEqual((result[i]["src_start"], result[i]["src_end"]), span if span else (None, None))

    def test_edge_texts(self):
        for text in EDGE_TEXTS:
            for lang in ("ko-KR", "en-US", "ja-JP"):
                with self.subTest(text=text[:20], lang=lang):
                    self.check(text, lang, None, MINI_WORDS)

    def test_random_adversarial_texts(self):
        rng = random.Random(20260928)
        for n in range(250):
            parts = []
            for _ in range(rng.choice([1, 2, 5, 15, 40, 120])):
                parts.append(rng.choice(FUZZ_FRAGMENTS))
                parts.append(rng.choice(FUZZ_SEPARATORS))
            if rng.random() < 0.5:
                parts.pop()
            text = "".join(parts)
            lang = rng.choice(["ko-KR", "en-US", "ja-JP", "zh-CN"])
            voice = rng.choice([None, "ko-KR", "en-US"])
            with self.subTest(n=n, text=text[:40], lang=lang, voice=voice):
                self.check(text, lang, voice, rng.choice([None, MINI_WORDS]))


