# JS 의 \s (node 로 확인한 목록)
JS_WS = frozenset("\t\n\x0b\x0c\r       　﻿"
                  + "".join(chr(c) for c in range(0x2000, 0x200B)))


def u16len(s):
    return len(s.encode("utf-16-le", "surrogatepass")) // 2


def words_of(spec):
    return {} if spec in (None, "none") else spec


def strip_ws(s):
    return "".join(c for c in s if c not in JS_WS)


class GoldenParityTest(unittest.TestCase):
    """확장 JS(HEAD) 결과와 조각 경계·원문 오프셋·읽기용 글·위치표(sourceIndex)가 같은지."""

    def test_hand_cases_match_extension(self):
        self.assertEqual(sorted(c["name"] for c in HAND_CASES), sorted(GOLDEN))
        for c in HAND_CASES:
            with self.subTest(name=c["name"]):
                expected = GOLDEN[c["name"]]
                text, lang = c["text"], c["lang"]
                voice = c.get("voiceLang") or lang
                segments = rt.build_segments(text, lang)
                seg_digest = hashlib.sha1("\x00".join(segments).encode("utf-8", "surrogatepass")).hexdigest()
                self.assertEqual(seg_digest, expected["segments_sha1"])
                alignment = rt.align_segments_to_source(text, segments)
                self.assertEqual(alignment is None, expected["alignment_null"])
                ranges = [alignment.segment_range(i) if alignment else None for i in range(len(segments))]
                self.assertEqual(ranges, expected["ranges"])
                spoken = [rt.make_spoken_text(s, voice, words_of(c["words"])) for s in segments]
                texts = [sp.text for sp in spoken]
                digest = hashlib.sha1("\x00".join(texts).encode("utf-8", "surrogatepass")).hexdigest()
                if "spoken" in expected:
                    self.assertEqual(texts, expected["spoken"])
                self.assertEqual(digest, expected["spoken_sha1"])
                src = [[sp.source_index(i) for i in range(len(sp.text) + 1)] for sp in spoken]
                self.assertEqual(hashlib.sha1(json.dumps(src).encode()).hexdigest(), expected["source_index_sha1"])

